'use strict'

const RAYMARINE_MANUFACTURER = [0x3b, 0x9f]

const STATE_PAYLOADS = {
  standby: [0x3b, 0x9f, 0xf0, 0x81, 0x86, 0x21, 0x02, 0xfd, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff],
  headinghold: [0x3b, 0x9f, 0xf0, 0x81, 0x86, 0x21, 0x01, 0xfe, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff],
  wind: [0x3b, 0x9f, 0xf0, 0x81, 0x86, 0x21, 0x23, 0xdc, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff],
  navigation: [0x3b, 0x9f, 0xf0, 0x81, 0x86, 0x21, 0x03, 0xfc, 0x3c, 0x42, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff]
}

const KEY_CODES = {
  '+1': [0x07, 0xf8],
  '+10': [0x08, 0xf7],
  '-1': [0x05, 0xfa],
  '-10': [0x06, 0xf9],
  tackPort: [0x21, 0xde],
  tackStarboard: [0x22, 0xdd]
}

function stateCommand(mode, dst) {
  const data = STATE_PAYLOADS[mode]
  if (!data) throw new Error(`Unsupported Raymarine state ${mode}`)
  return { pgn: 126720, prio: 3, dst, data: Buffer.from(data) }
}

function keyCommand(key, dst = 255) {
  const code = KEY_CODES[key]
  if (!code) throw new Error(`Unsupported Raymarine key ${key}`)
  return {
    pgn: 126720,
    prio: 3,
    dst,
    data: Buffer.from([
      ...RAYMARINE_MANUFACTURER,
      0xf0, 0x81, 0x86, 0x21,
      ...code,
      0x07, 0x01, 0x02,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0xff, 0xff, 0xff
    ])
  }
}

function decodePilotMode(data) {
  if (!Buffer.isBuffer(data)) return undefined
  const signature = Buffer.from([0x3b, 0x9f, 0xf0, 0x81, 0x84])
  const pos = data.indexOf(signature)
  if (pos < 0 || data.length <= pos + 8) return undefined
  const mode = data[pos + 8]
  if (mode === 0x42) return 'headinghold'
  if (mode === 0x46) return 'wind'
  if ([0x40, 0x44, 0x48].includes(mode)) return 'standby'
  if (mode === 0x4a) return 'navigation'
  return undefined
}

module.exports = { stateCommand, keyCommand, decodePilotMode }
